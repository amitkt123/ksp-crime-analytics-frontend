// One-time local generator: reads the already-committed per-district station boundary
// fixtures (public/data/stations/*.geojson) and writes each station's ring-average
// centroid keyed by unitId, for mock-mode use (mockData.ts's mockLocation jitters
// around these instead of a Karnataka-wide random spot). Not part of the build --
// run manually: node scripts/build-station-centroids.mjs
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const STATIONS_DIR = 'public/data/stations';
const FIXTURE_OUT_FILE = 'src/api/generatedStationCentroids.ts';
const COORD_PRECISION = 5;

function ringCentroid(ring) {
  let sx = 0;
  let sy = 0;
  for (const [x, y] of ring) {
    sx += x;
    sy += y;
  }
  return [sx / ring.length, sy / ring.length];
}

function geometryCentroid(geometry) {
  if (geometry.type === 'Polygon') return ringCentroid(geometry.coordinates[0]);
  const biggest = geometry.coordinates.reduce((a, b) => (a[0].length >= b[0].length ? a : b));
  return ringCentroid(biggest[0]);
}

function round(n) {
  return Number(n.toFixed(COORD_PRECISION));
}

async function main() {
  const files = (await readdir(STATIONS_DIR)).filter((f) => f.endsWith('.geojson'));
  const centroids = {};

  for (const file of files) {
    const collection = JSON.parse(await readFile(path.join(STATIONS_DIR, file), 'utf8'));
    for (const feature of collection.features) {
      const [lng, lat] = geometryCentroid(feature.geometry);
      centroids[feature.properties.unitId] = [round(lng), round(lat)];
    }
  }

  const fixtureSource = [
    '// Generated by scripts/build-station-centroids.mjs -- do not hand-edit.',
    '// [lng, lat] ring-average centroid per unitId, derived from public/data/stations/*.geojson.',
    'export const STATION_CENTROIDS: Record<number, [number, number]> = ' +
      JSON.stringify(centroids, null, 2) +
      ';',
    '',
  ].join('\n');
  await writeFile(FIXTURE_OUT_FILE, fixtureSource);
  console.log(`wrote ${FIXTURE_OUT_FILE}: ${Object.keys(centroids).length} station centroids`);
}

main();
